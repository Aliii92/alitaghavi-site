  owner text not null default 'ali',
  title text not null,
  area text not null,
  building text not null,
  category text not null default 'resale-off-plan',
  inventory_type text not null default 'Resale Off-Plan',
  property_type text,
  bedrooms text,
  size text,
  price text,
  view text,
