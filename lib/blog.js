function normalizeLocale(locale = "en") {
  return locale === "fa" ? "fa" : "en";
}

function localizeField(value, locale = "en") {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    const normalizedLocale = normalizeLocale(locale);
    return value[normalizedLocale] || value.en || Object.values(value)[0] || "";
  }
  return value || "";
}

function localizePost(post, locale = "en") {
  return {
    slug: post.slug,
    date: post.date,
    coverImage: post.coverImage || "/dubai-hero.png",
    title: localizeField(post.title, locale),
    excerpt: localizeField(post.excerpt, locale),
    author: localizeField(post.author, locale),
    category: localizeField(post.category, locale),
    content: localizeField(post.content, locale)
  };
}

export function getAllBlogPosts(locale = "en") {
  return blogPosts
    .slice()
    .sort((left, right) => new Date(right.date) - new Date(left.date))
    .map((post) => localizePost(post, locale));
}

export function getBlogPostBySlug(slug, locale = "en") {
  const post = blogPosts.find((item) => item.slug === slug);
  return post ? localizePost(post, locale) : null;
}

export function getBlogSlugs() {
  return blogPosts.map((post) => post.slug);
}
